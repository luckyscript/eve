package com.eve.android

import com.eve.android.crypto.RemoteCrypto
import com.eve.android.crypto.CryptoSession
import com.eve.android.data.PendingQueue
import com.eve.android.data.PendingRun
import com.eve.android.data.resolvedRunStatus
import com.eve.android.pairing.Invite
import com.eve.android.pairing.Pairing
import java.util.UUID
import org.junit.Assert.*
import org.junit.Test

class ProtocolTest {
    // Public deterministic test material, never a deployment credential.
    private val secret = ByteArray(32) { it.toByte() }
    private val cn = ByteArray(32) { (it + 32).toByte() }
    private val sn = ByteArray(32) { (it + 64).toByte() }
    private fun invite() = Invite(1, "https://relay.example", "public-test-route-0001", UUID.randomUUID().toString(), RemoteCrypto.encode(secret), 2000L, "Test desktop")
    private fun rejects(block: () -> Unit) { try { block(); fail("expected rejection") } catch (_: IllegalArgumentException) {} }

    @Test fun proofsAreDirectionalAndVerified() {
        val c = RemoteCrypto.encode(cn); val s = RemoteCrypto.encode(sn)
        val proof = RemoteCrypto.proof(secret, "server", "p", "c", c, s)
        assertEquals("4gwLQSRWrN862oKgEM19oYyr_ZMAx7yQn3iD4cTPnH8", proof) // independently generated by Node crypto
        assertTrue(RemoteCrypto.verify(proof, proof))
        assertFalse(RemoteCrypto.verify(proof, RemoteCrypto.proof(secret, "client", "p", "c", c, s)))
        assertFalse(RemoteCrypto.verify(proof, "invalid"))
    }
    @Test fun derivedKeysAreDirectional() {
        assertEquals(32, RemoteCrypto.derive(secret, cn, sn, "s2c").size)
        assertEquals("56791f49cc7f09162b6168ef07317501eff385f78c01d89c3a52b4a460cb223e", RemoteCrypto.derive(secret, cn, sn, "s2c").joinToString("") { "%02x".format(it) })
        assertFalse(RemoteCrypto.derive(secret, cn, sn, "s2c").contentEquals(RemoteCrypto.derive(secret, cn, sn, "c2s")))
    }
    @Test fun serverPacketDecryptsAndReplayIsRejected() {
        val session = CryptoSession(secret, cn, sn)
        val key = RemoteCrypto.derive(secret, cn, sn, "s2c")
        val packet = RemoteCrypto.encode(RemoteCrypto.crypt(true, key, "s2c", 1L, "ready".toByteArray()))
        assertEquals("ready", session.decrypt(1L, packet).toString(Charsets.UTF_8))
        rejects { session.decrypt(1L, packet) }
        rejects { session.decrypt(3L, packet) }
    }
    @Test fun wrongAuthenticationTagFails() {
        val session = CryptoSession(secret, cn, sn)
        val key = RemoteCrypto.derive(secret, cn, sn, "s2c")
        val packet = RemoteCrypto.crypt(true, key, "s2c", 1L, "ready".toByteArray())
        packet[packet.lastIndex] = (packet.last().toInt() xor 1).toByte()
        var rejected = false
        try { session.decrypt(1L, RemoteCrypto.encode(packet)) } catch (_: Exception) { rejected = true }
        assertTrue(rejected)
    }
    @Test fun cleartextOnlyAllowedForExplicitLocalDevelopment() {
        rejects { Pairing.relay("http://relay.example", true) }
        rejects { Pairing.relay("http://localhost:8080", false) }
        assertEquals("localhost", Pairing.relay("http://localhost:8080", true).host)
        rejects { Pairing.relay("https://user:password@relay.example", false) }
        rejects { Pairing.relay("https://relay.example/path", false) }
    }
    @Test fun inviteExpiryDoesNotExpireBoundReconnect() {
        val i = invite()
        rejects { Pairing.validate(i, false, imported = true, now = 3000) }
        Pairing.validate(i, false, imported = false, now = 3000)
    }
    @Test fun pendingRequestIdsSurviveAndDeduplicate() {
        val run = PendingRun("id", "pair", "prompt")
        val saved = PendingQueue.add(emptyList(), run)
        assertEquals(1, PendingQueue.add(saved, run).size)
        assertEquals(listOf("id"), PendingQueue.recover(saved, "pair"))
        assertTrue(PendingQueue.recover(saved, "other-pair").isEmpty())
        rejects { PendingQueue.add(saved, run.copy(prompt = "different")) }
    }
    @Test fun completedTransportMustNotMaskFailedTask() {
        assertEquals("failed", resolvedRunStatus("completed", "failed"))
        assertEquals("completed", resolvedRunStatus("completed", "completed"))
        assertEquals("failed", resolvedRunStatus("completed", null))
    }
}
